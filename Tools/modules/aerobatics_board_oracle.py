"""Produce the controller oracle using the actual H743 Lua engine and C math."""

import hashlib
import math
import struct
import subprocess

from test_aerobatics_controller import lua_trace
from test_aerobatics_path import LUA_DIR
from test_driver_probe import ControlledPhysics
from test_runtime import ROOT
from test_threads import gen_board
from test_threads import renode_data
from test_threads import run


def generate(tmp_path, emulator, variant):
    tmp_path.mkdir(parents=True, exist_ok=True)
    executable = ROOT / 'build/MatekH743/bin/arduplane'
    defaults = (ROOT / 'Tools/modules/aerobatics-oracle.parm').read_bytes().rstrip()
    embedded = subprocess.check_output(['python3', str(ROOT / 'Tools/scripts/apj_tool.py'), '--show', str(executable)])
    assert embedded.split(b'\n', 2)[2].strip() == defaults, \
        'Build H743 Plane with the exact aerobatics oracle embedded defaults'
    print(f'Lua ELF SHA256 {hashlib.sha256(executable.read_bytes()).hexdigest()} '
          f'mtime_ns={executable.stat().st_mtime_ns}', flush=True)
    generated = gen_board.generate(ROOT, 'MatekH743', tmp_path / 'generated', uart_port=0, state_dir=tmp_path)
    data = renode_data.ensure_mcu_data(generated['mcu_type'])
    sdcard = run.make_fat_image(tmp_path / 'sdcard.img', 16 * 1024 * 1024, fat_bits=16)
    subprocess.run(['mmd', '-i', str(sdcard), '::/APM', '::/APM/scripts'], check=True)
    # Use a trace already generated by the same test source, not a manually
    # maintained alternative implementation of the Lua equations.
    source = tmp_path / 'golden.lua'
    source_text = lua_trace(variant).replace('local real_logger = logger', '''
local golden_file = assert(io.open("/APM/aerobatics-golden.bin", "wb"))
local real_logger = {write=function(name,labels,fmt,...)
 local values = {...}
 for i=1,#values do values[i] = string.pack("<f",values[i]) end
 golden_file:write(table.concat(values))
end}
''')
    source_text = source_text.replace('gcs:send_text(6,"AEROP Lua controller done")',
                                      'golden_file:close()\n gcs:send_text(6,"AEROP Lua controller done")')
    source.write_text(source_text)
    subprocess.run(['mcopy', '-i', str(sdcard), str(source), '::/APM/scripts/golden.lua'], check=True)
    subprocess.run(['mcopy', '-i', str(sdcard), str(LUA_DIR / 'Schedules/AirShow.txt'),
                    '::/APM/scripts/trick72.txt'], check=True)
    physics = ControlledPhysics()
    physics.start()
    try:
        script = '''
$elf=@%s
$mcu_svd=@%s
$sdcard=@%s
$vector_base=0x%X
include @%s
sysbus.uart7Host CreateFileBackend @%s true
sysbus.physics Connect %u "stationary" -35.363261 149.165230 584 0 400
emulation SetGlobalAdvanceImmediately true
emulation RunFor "60"
''' % (
            executable, data['svd'], sdcard, generated['app_base'], generated['resc'],
            tmp_path / 'uart.bin', physics.port,
        )
        output = emulator(script, timeout=120)
    finally:
        physics.stop()
    (tmp_path / 'renode.log').write_text(output)
    subprocess.run(['mdir', '-i', str(sdcard), '::/APM'], check=True)
    subprocess.run(['mcopy', '-s', '-i', str(sdcard), '::/APM/LOGS', str(tmp_path / 'logs')], check=True)
    subprocess.run(['mcopy', '-i', str(sdcard), '::/APM/aerobatics-golden.bin', str(tmp_path / 'golden.bin')], check=True)
    oracle = (tmp_path / 'golden.bin').read_bytes()
    assert len(oracle) == 512 * 33 * 4
    assert all(math.isfinite(v[0]) for v in struct.iter_unpack('<f', oracle))
    return oracle
