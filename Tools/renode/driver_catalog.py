def i2c_endpoints(device):
    """Return the model/address endpoints occupied by an I2C attachment."""
    endpoints = device.get('i2c_endpoints')
    if endpoints is not None:
        return endpoints
    return ({'model': device.get('model'), 'address': device.get('address')},)


