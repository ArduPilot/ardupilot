def elf_symbol(elf, name):
    '''address of a symbol in the ELF, or None'''
    nm = shutil.which('arm-none-eabi-nm') or shutil.which('nm')
    if nm is None:
        return None
    try:
        out = subprocess.check_output([nm, str(elf)], stderr=subprocess.DEVNULL).decode()
    except (OSError, subprocess.CalledProcessError):
        return None
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[2] == name:
            return int(parts[0], 16)
    return None


def cpp_symbols(elf):
    '''Demangled ELF (address, size) pairs, keyed by complete names.'''
    nm = shutil.which('arm-none-eabi-nm') or shutil.which('nm')
    if nm is None:
        return {}
    try:
        out = subprocess.check_output(
            [nm, '-C', '-S', str(elf)], stderr=subprocess.DEVNULL
        ).decode()
    except (OSError, subprocess.CalledProcessError):
        return {}
    symbols = {}
    for line in out.splitlines():
        parts = line.split(None, 3)
        if len(parts) != 4:
            continue
        try:
            symbols[parts[3]] = (int(parts[0], 16), int(parts[1], 16))
        except ValueError:
            pass
    return symbols


def elf_data(elf, address, size):
    '''Read bytes from a loadable ELF address using objdump.'''
    objdump = shutil.which('arm-none-eabi-objdump') or shutil.which('objdump')
    if objdump is None:
        sys.exit('objdump is required for the PR 33933 reproduction')
    try:
        out = subprocess.check_output(
            [objdump, '-s', '--start-address=0x%X' % address,
             '--stop-address=0x%X' % (address + size), str(elf)],
            stderr=subprocess.STDOUT,
        ).decode()
    except (OSError, subprocess.CalledProcessError) as error:
        sys.exit('failed to read data from %s: %s' % (elf, error))
    data = bytearray()
    for line in out.splitlines():
        fields = line.split()
        if not fields or not re.fullmatch(r'[0-9a-fA-F]+', fields[0]):
            continue
        for field in fields[1:]:
            if not re.fullmatch(r'[0-9a-fA-F]{8}', field):
                break
            data.extend(bytes.fromhex(field))
    if len(data) != size:
        sys.exit('expected %u bytes at 0x%X in %s, found %u' %
                 (size, address, elf, len(data)))
    return data


def group_member_offset(elf, address, size, index):
    '''Find an AP_Param GroupInfo member offset by its parameter index.'''
    data = elf_data(elf, address, size)
    group_info_size = 16
    for entry in range(0, len(data), group_info_size):
        if entry + group_info_size > len(data):
            break
        if data[entry + 14] == index:
            return int.from_bytes(data[entry + 4:entry + 8], 'little')
    sys.exit('PR 33933 reproduction: parameter index %u not found' % index)


def serial_dma_offsets(elf):
    '''Derive RCOutput serial_group and pwm_group dma_handle offsets.'''
    objdump = shutil.which('arm-none-eabi-objdump') or shutil.which('objdump')
    if objdump is None:
        sys.exit('objdump is required for the PR 33933 reproduction')
    try:
        out = subprocess.check_output(
            [objdump, '-d', '-C', str(elf)], stderr=subprocess.STDOUT
        ).decode()
    except (OSError, subprocess.CalledProcessError) as error:
        sys.exit('failed to disassemble %s: %s' % (elf, error))
    marker = ('<ChibiOS::RCOutput::serial_write_bytes(unsigned char const*, '
              'unsigned short)>:')
    start = out.find(marker)
    if start < 0:
        sys.exit('PR 33933 reproduction: RCOutput::serial_write_bytes not found')
    body = out[start:out.find('\n\n', start)]
    serial_group = re.search(r'ldr(?:\.w)?\s+r4, \[r0, #(\d+)\]', body)
    dma_handle = re.search(r'ldr(?:\.w)?\s+r0, \[r4, #(\d+)\]', body)
    if serial_group is None or dma_handle is None:
        sys.exit('PR 33933 reproduction: could not derive RCOutput layout')
    return int(serial_group.group(1)), int(dma_handle.group(1))


def blheli_initialized_offset(elf):
    '''Derive the AP_BLHeli::initialised member offset from init().'''
    objdump = shutil.which('arm-none-eabi-objdump') or shutil.which('objdump')
    if objdump is None:
        sys.exit('objdump is required for the PR 33933 reproduction')
    try:
        out = subprocess.check_output(
            [objdump, '-d', '-C', str(elf)], stderr=subprocess.STDOUT
        ).decode()
    except (OSError, subprocess.CalledProcessError) as error:
        sys.exit('failed to disassemble %s: %s' % (elf, error))
    marker = '<AP_BLHeli::init(unsigned long, AP_HAL::RCOutput::output_mode)>:'
    start = out.find(marker)
    if start < 0:
        sys.exit('PR 33933 reproduction: AP_BLHeli::init not found')
    body = out[start:out.find('\n\n', start)]
    initialised = re.search(r'strb(?:\.w)?\s+r3, \[r0, #(\d+)\]', body)
    if initialised is None:
        sys.exit('PR 33933 reproduction: could not derive AP_BLHeli layout')
    return int(initialised.group(1))


def pr33933_commands(elf, expected):
    '''Hooks for a deterministic test of the stale BLHeli motor mapping.

       The firmware must use params/pr33933.parm. For the failure cases,
       the hook changes SERVO_BLH_MASK from 16 to zero after
       AP_BLHeli::init(). The cached motor mask still names output 5, while
       the missing dynamic Motor1 assignment falls back to output 1. The
       valid control leaves the mask unchanged.
    '''
    symbols = cpp_symbols(elf)

    def monitor_script(script):
        return script.replace('\\', '\\\\').replace('"', '\\"')

    def required(name):
        info = symbols.get(name)
        if info is None:
            sys.exit("PR 33933 reproduction: symbol not found: %s" % name)
        return info

    singleton, _ = required('AP_BLHeli::_singleton')
    update, _ = required('AP_BLHeli::update()')
    var_info, var_info_size = required('AP_BLHeli::var_info')
    serial_write, _ = required(
        'ChibiOS::RCOutput::serial_write_bytes(unsigned char const*, unsigned short)'
    )
    channel_mask = group_member_offset(elf, var_info, var_info_size, 1)
    run_test = group_member_offset(elf, var_info, var_info_size, 3)
    serial_group_offset, dma_handle_offset = serial_dma_offsets(elf)
    initialised_offset = blheli_initialized_offset(elf)

    if expected == 'valid':
        trigger = (
            'obj=machine.SystemBus.ReadDoubleWord(0x%X); '
            'ready=obj != 0 and machine.SystemBus.ReadByte(obj+%u) != 0; '
            'machine.SystemBus.WriteByte(obj+%u, 1) if ready else None; '
            'self.InfoLog("PR33933: retained valid output 5 mapping") if ready else None'
            % (singleton, initialised_offset, run_test)
        )
    else:
        trigger = (
            'obj=machine.SystemBus.ReadDoubleWord(0x%X); '
            'ready=obj != 0 and machine.SystemBus.ReadByte(obj+%u) != 0; '
            'machine.SystemBus.WriteDoubleWord(obj+%u, 0) if ready else None; '
            'machine.SystemBus.WriteByte(obj+%u, 1) if ready else None; '
            'self.InfoLog("PR33933: changed SERVO_BLH_MASK from 16 to 0 after BLHeli init") if ready else None'
            % (singleton, initialised_offset, channel_mask, run_test)
        )
    observe = (
        'rcout=self.GetRegisterUlong(0); '
        'group=machine.SystemBus.ReadDoubleWord(rcout+%u); '
        'handle=machine.SystemBus.ReadDoubleWord(group+%u); '
        'self.InfoLog("PR33933: selected pwm_group DMA handle=0x{0:X}", handle); '
        'self.RemoveHooksAt(0x%X); self.RemoveHooksAt(0x%X)'
        % (serial_group_offset, dma_handle_offset, serial_write, update)
    )
    if expected == 'fixed':
        observe += (
            '; self.ErrorLog("PR33933: fixed build unexpectedly reached serial output")'
            '; machine.PauseAndRequestEmulationPause()'
        )
    elif expected == 'valid':
        observe += (
            '; self.InfoLog("PR33933: valid mapping reached serial DMA") if handle != 0 else '
            'self.ErrorLog("PR33933: valid mapping has a null DMA handle")'
            '; machine.PauseAndRequestEmulationPause()'
        )
    commands = [
        'logLevel 3 nvic',
        'logLevel 3 flashController',
        'logLevel 3 bdma',
        'logLevel 3 adcM1S2',
        'logLevel 3 adc3',
        'logLevel 3 usart1',
        'logLevel 3 usart2',
        'logLevel 3 usart3',
        'logLevel 3 uart4',
        'logLevel 3 uart8',
        'logLevel 3 timer1',
        'logLevel 3 timer3',
        'logLevel 3 timer4',
        'logLevel 3 timer5',
        'cpu AddHook 0x%X "%s"' % (update, monitor_script(trigger)),
        'cpu AddHook 0x%X "%s"' % (serial_write, monitor_script(observe)),
    ]

    if expected == 'vulnerable':
        crash_start, _ = required('CrashCatcher_DumpStart')
        crash_end, _ = required('CrashCatcher_DumpEnd')
        crash = 'self.ErrorLog("PR33933: vulnerable build entered CrashCatcher")'
        dumped = (
            'self.ErrorLog("PR33933: CrashCatcher finished writing the dump"); '
            'machine.PauseAndRequestEmulationPause()'
        )
        commands.append('cpu AddHook 0x%X "%s"' % (crash_start, monitor_script(crash)))
        commands.append('cpu AddHook 0x%X "%s"' % (crash_end, monitor_script(dumped)))
    elif expected == 'guarded':
        internal_error, _ = required(
            'AP_InternalError::error(AP_InternalError::error_t, unsigned short)'
        )
        check = (
            'code=self.GetRegisterUlong(1); '
            'self.InfoLog("PR33933: AP_InternalError code=0x{0:X}", code); '
            'machine.PauseAndRequestEmulationPause() if code == 0x00100000 else None'
        )
        commands.append(
            'cpu AddHook 0x%X "%s"' % (internal_error, monitor_script(check))
        )
    elif expected == 'fixed':
        serial_end, _ = required('AP_BLHeli::serial_end()')
        success = (
            'obj=machine.SystemBus.ReadDoubleWord(0x%X); '
            'mask=machine.SystemBus.ReadDoubleWord(obj+%u) if obj != 0 else 16; '
            'self.InfoLog("PR33933: fixed build rejected stale motor mapping") if mask == 0 else None; '
            'self.RemoveHooksAt(0x%X) if mask == 0 else None; '
            'machine.PauseAndRequestEmulationPause() if mask == 0 else None'
            % (singleton, channel_mask, update)
        )
        commands.append(
            'cpu AddHook 0x%X "%s"' % (serial_end, monitor_script(success))
        )
    return commands


def hwdef_value(hwdef_h, name):
    '''integer value of a #define in a generated hwdef.h, or None'''
    try:
        for line in open(hwdef_h):
            parts = line.split()
            if len(parts) >= 3 and parts[0] == '#define' and parts[1] == name:
                try:
                    return int(parts[2], 0)
                except ValueError:
                    return None
    except OSError:
        pass
    return None


def storage_region(hwdef_h):
    '''(base, size) of the AP_FlashStorage sectors, which must read 0xFF.
       AP_FlashStorage always uses two sectors starting at
       STORAGE_FLASH_PAGE; the sector map is per MCU family.'''
    page = hwdef_value(hwdef_h, 'STORAGE_FLASH_PAGE')
    if page is None:
        return None
    text = open(hwdef_h).read() if os.path.exists(hwdef_h) else ''
    if 'STM32H7' in text:
        sectors = [128 * 1024] * 16          # uniform on the H743
    elif 'STM32F7' in text:
        # F765/F767 flight-controller hwdefs use the 2 MiB dual-bank layout.
        bank = [16 * 1024] * 4 + [64 * 1024] + [128 * 1024] * 7
        sectors = bank + bank
    elif 'STM32F4' in text:
        sectors = [16 * 1024] * 4 + [64 * 1024] + [128 * 1024] * 7
    else:
        return None
    if page + 1 >= len(sectors):
        return None
    base = 0x08000000 + sum(sectors[:page])
    return base, sectors[page] + sectors[page + 1]


def make_erased(path, size):
    '''Create a persistent erased image without replacing existing state.'''
    if path.exists():
        if path.stat().st_size != size:
            sys.exit('%s is %u bytes; expected %u (move it aside to reinitialize)' %
                     (path, path.stat().st_size, size))
        return path
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, 'wb') as f:
        f.write(b'\xff' * size)
    return path


def make_fat_image(path, size, fat_bits=32):
    '''Create a persistent FAT image without replacing existing state.'''
    if path.exists():
        if path.stat().st_size != size:
            sys.exit('%s is %u bytes; expected %u (move it aside to reinitialize)' %
                     (path, path.stat().st_size, size))
        return path
    mkfs = shutil.which('mkfs.fat')
    if mkfs is None:
        sys.exit('mkfs.fat is required to create %s' % path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, 'wb') as f:
        f.truncate(size)
    try:
        subprocess.check_call([mkfs, '-F', str(fat_bits), '-n', 'ARDUPILOT', str(path)],
                              stdout=subprocess.DEVNULL)
    except (OSError, subprocess.CalledProcessError):
        sys.exit('failed to create FAT%u image %s' % (fat_bits, path))
    return path


def make_persistence_repl(path, regions):
    '''Generate helpers which save mapped-memory regions on pause/exit.'''
    lines = [
        '// GENERATED by Tools/renode/run.py.',
        '// Persistent regions derived from the selected hwdef and ELF.',
        '',
    ]
    for name, image, address, size in regions:
        lines += [
            '%s: Miscellaneous.AP_PersistentMemory @ none' % name,
            '    fileName: %s' % json.dumps(str(image)),
            '    address: 0x%08X' % address,
            '    size: 0x%X' % size,
            '',
        ]
    path.write_text('\n'.join(lines))
    return path


def has_debug_info(elf):
    '''True if the ELF carries DWARF. Without it gdb can only show
       addresses, so it is worth failing early rather than after two
       windows have opened.'''
    readelf = shutil.which('arm-none-eabi-readelf') or shutil.which('readelf')
    if readelf is None:
        return None
    try:
        out = subprocess.check_output([readelf, '-S', str(elf)],
                                      stderr=subprocess.DEVNULL).decode()
    except (OSError, subprocess.CalledProcessError):
        return None
    return '.debug_info' in out


def make_runtime_elf(source, destination):
    '''Copy an ELF without DWARF for Renode while GDB keeps the original.

       Reverse execution serializes Renode's ELF metadata into snapshots. A
       debug ArduPilot ELF carries tens of MiB of DWARF, so loading that copy
       into Renode makes the first snapshot unnecessarily large and slow.
       --strip-debug retains the normal symbol table used by Renode hooks.
    '''
    objcopy = shutil.which('arm-none-eabi-objcopy') or shutil.which('objcopy')
    if objcopy is None:
        sys.exit('objcopy is required for a GDB launch')
    try:
        subprocess.check_call(
            [objcopy, '--strip-debug', str(source), str(destination)],
            stderr=subprocess.STDOUT,
        )
    except (OSError, subprocess.CalledProcessError) as error:
        sys.exit('failed to make Renode runtime ELF: %s' % error)
    return destination


def find_terminal():
    for term in ('xterm', 'x-terminal-emulator', 'konsole', 'gnome-terminal'):
        path = shutil.which(term)
        if path:
            return path
    return None


def find_renode(explicit, here):
    if explicit:
        return explicit
    env = os.environ.get('RENODE')
    if env:
        return env
    # gitignored symlink next to this script: the way to pin a local
    # (ideally patched) build without any environment setup
    local = here / 'renode'
    if local.exists():
        return str(local)
    path = shutil.which('renode')
    if path:
        return path
    for candidate in ('/opt/renode/renode', '/usr/local/bin/renode'):
        if Path(candidate).exists():
            return candidate
    sys.exit("no renode found: pass --renode, set $RENODE, put renode on\n"
             "PATH, or symlink your build here:\n"
             "  ln -s /path/to/renode %s" % local)


def main():
    root = Path(__file__).resolve().parents[2]
    boards = gen_board.supported_boards(root)

    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('board', nargs='?',
                        help='supported ChibiOS flight-controller board name')
    parser.add_argument('--list', action='store_true', help='list available boards')
    parser.add_argument('--vehicle', default='arducopter',
                        help='vehicle firmware to run (default: arducopter)')
    parser.add_argument('--elf', help='firmware ELF (default: build/<board>/bin/<vehicle>)')
    parser.add_argument('--renode', help='renode executable to use')
    parser.add_argument('--state-dir',
                        help='persistent board state directory '
                             '(default: renode/<board>)')
    parser.add_argument('--serial', type=int,
                        help='SERIAL_ORDER index exposed on the TCP socket '
                             '(default: first hardware UART)')
    parser.add_argument('--uart-port', type=int, default=5762,
                        help='TCP port for the selected UART (default: 5762)')
    parser.add_argument('--unthrottled', action='store_true',
                        help='run as fast as possible instead of pacing at real time')
    parser.add_argument('--can', action='store_true',
                        help='bridge CAN1 and CAN2 to mcast:0 and mcast:1')
    parser.add_argument('--ethernet-tap', metavar='INTERFACE',
                        help='connect the emulated Ethernet MAC to this host TAP')
    parser.add_argument('--port', type=int,
                        help='telnet monitor on this port instead of the interactive console')
    parser.add_argument('--exec', dest='extra', action='append', default=[],
                        help='extra monitor command to run after start (repeatable)')
    parser.add_argument('--gdb', action='store_true',
                        help='start a gdb server, halted at reset, and attach '
                             'gdb in a terminal window')
    parser.add_argument('--reverse-debug', action='store_true',
                        help='with --gdb, enable Renode reverse execution and snapshots')
    parser.add_argument('--reverse-gdb-limit', type=int, default=1000,
                        help='maximum reverse-debug history in guest instructions '
                             '(default: 1000, 0: unlimited)')
    parser.add_argument('--gdb-port', type=int, default=3333)
    parser.add_argument('--renode-gdb-port', type=int,
                        help='internal Renode GDB port (default: --gdb-port + 1)')
    parser.add_argument('--gdb-bin', help='gdb to use (default: arm-none-eabi-gdb)')
    parser.add_argument('--no-xterm', action='store_true',
                        help='with --gdb, print the attach command instead of '
                             'opening a terminal')
    parser.add_argument('--reproduce-pr33933',
                        choices=('vulnerable', 'guarded', 'fixed', 'valid'),
                        help='reproduce the stale BLHeli motor mapping and '
                             'observe the expected firmware behavior')
    args = parser.parse_args()

    if args.reverse_debug and not args.gdb:
        parser.error('--reverse-debug requires --gdb')
    if args.reverse_gdb_limit < 0:
        parser.error('--reverse-gdb-limit cannot be negative')

    if args.list or not args.board:
        print('\n'.join(boards))
        return 0 if args.list else 1
    if args.board not in boards:
        sys.exit("unknown board '%s' (have: %s)" % (args.board, ', '.join(boards)))

    elf = Path(args.elf) if args.elf else root / 'build' / args.board / 'bin' / args.vehicle
    if not elf.exists():
        target = {'arducopter': 'copter', 'arduplane': 'plane', 'ardurover': 'rover',
                  'ardusub': 'sub', 'antennatracker': 'antennatracker'}.get(args.vehicle, args.vehicle)
        sys.exit("no firmware at %s - build it first:\n"
                 "  ./waf configure --board %s && ./waf %s" % (elf, args.board, target))

    state_dir = (Path(args.state_dir).expanduser() if args.state_dir else
                 root / 'renode' / args.board).resolve()
    state_dir.mkdir(parents=True, exist_ok=True)

    # Generate the board overlay from the production hwdef compiler outputs on
    # every invocation. This is under one second on the supported families and
    # ensures hwdef.dat/hwdef-bl.dat, not checked-in Renode board copies, are
    # authoritative for pins, buses, DMA, flash layout, and devices.
    outdir = root / 'build' / args.board / 'renode'
    serial_index = 3 if args.reproduce_pr33933 and args.serial is None else args.serial
    try:
        generated = gen_board.generate(
            root, args.board, outdir / 'generated', serial_index, args.uart_port,
            state_dir, quiet_peripherals=not args.reverse_debug)
    except (OSError, ValueError) as error:
        sys.exit('failed to generate Renode board: %s' % error)
    for warning in generated['warnings']:
        print('warning: %s' % warning, file=sys.stderr)
    if args.can and not generated['can_buses']:
        sys.exit('%s has no generated CAN peripherals' % args.board)
    if args.ethernet_tap and not generated['has_ethernet']:
        sys.exit('%s has no generated Ethernet peripheral' % args.board)

    # Persistent flash images begin erased, are loaded after the ELF, and are
    # saved by AP_PersistentMemory when the machine pauses or exits. Regions
    # remain build-specific, so derive them from hwdef.h and the selected ELF.
    initial_loads = []
    persistent_regions = []
    storage = storage_region(generated['hwdef_h'])
    if storage and not generated['has_fram']:
        base, size = storage
        img = make_erased(state_dir / 'storage.img', size)
        initial_loads.append('sysbus LoadBinary @%s 0x%08X' % (img, base))
        persistent_regions.append(('persistentStorage', img, base, size))
    crash_base = elf_symbol(elf, '__crash_log_base__')
    crash_end = elf_symbol(elf, '__crash_log_end__')
    if crash_base and crash_end and crash_end > crash_base:
        size = crash_end - crash_base
        img = make_erased(state_dir / 'crashlog.img', size)
        initial_loads.append('sysbus LoadBinary @%s 0x%08X' % (img, crash_base))
        persistent_regions.append(('persistentCrashlog', img, crash_base, size))
    if generated['has_fram']:
        make_erased(state_dir / 'fram.img', generated['fram_size'])

    pre_vars = []
    if generated['has_sdcard']:
        if args.reverse_debug:
            # Renode serializes file-backed storage into every reverse snapshot.
            # Keep the normal 256 MiB persistent card out of that path: a small
            # FAT16 scratch filesystem is ample for a debugging session and
            # reduces each CubeBlack snapshot by roughly 240 MiB.
            img = make_fat_image(
                outdir / 'reverse-sdcard-16m.img', 16 * 1024 * 1024,
                fat_bits=16)
        else:
            img = make_fat_image(state_dir / 'sdcard.img', 256 * 1024 * 1024)
        pre_vars.append('$sdcard=@%s' % img)

    persistence_repl = None
    if persistent_regions:
        persistence_repl = make_persistence_repl(
            outdir / 'generated' / 'persistent.repl', persistent_regions)

    renode = find_renode(args.renode, root / 'Tools' / 'renode')

    runtime_elf = elf
    if args.reverse_debug:
        runtime_elf = make_runtime_elf(elf, outdir / 'gdb-runtime.elf')

    monitor = ['-P', str(args.port)] if args.port else ['--console']
    commands = ['$repo=@%s' % root,
                '$elf=@%s' % runtime_elf] + pre_vars + [
                'include @%s' % generated['resc']] + initial_loads
    if args.can:
        for index, bus in enumerate(generated['can_buses']):
            commands.append('sysbus.%sMcast Bus %u' % (bus.lower(), index))
    if args.ethernet_tap:
        commands += [
            'emulation CreateSwitch "ethernetSwitch"',
            'connector Connect sysbus.ethernet ethernetSwitch',
            'emulation CreateTap %s "ethernetTap" false' %
            json.dumps(args.ethernet_tap),
            'connector Connect host.ethernetTap ethernetSwitch',
        ]
    if persistence_repl is not None:
        commands.append('machine LoadPlatformDescription @%s' % persistence_repl)
    if args.unthrottled:
        commands.append('emulation SetGlobalAdvanceImmediately true')
    if args.reproduce_pr33933:
        if args.board != 'BlitzWingH743' or args.vehicle != 'arduplane':
            sys.exit('--reproduce-pr33933 requires BlitzWingH743 --vehicle arduplane')
        if args.gdb:
            sys.exit('--reproduce-pr33933 cannot be combined with --gdb')
        commands += pr33933_commands(elf, args.reproduce_pr33933)

    gdb_proc = None
    gdb_proxy_proc = None
    if args.gdb:
        dbg = has_debug_info(elf)
        if dbg is False:
            sys.exit('%s has no .debug_info; gdb would only show addresses.\n'
                     'Rebuild with:\n'
                     '  ./waf configure --board %s --debug && ./waf copter'
                     % (elf, args.board))
        if dbg is None:
            print('no readelf found, so not checking the ELF for debug info')
        gdb = args.gdb_bin or 'arm-none-eabi-gdb'
        outdir = root / 'build' / args.board / 'renode'
        outdir.mkdir(parents=True, exist_ok=True)
        launcher = outdir / 'gdb.sh'
        launcher.write_text(GDB_LAUNCH.replace('$PORT', str(args.gdb_port))
                                      .replace('$GDB', gdb)
                                      .replace('$ELF', str(elf))
                                      .replace('$READY', str(outdir / 'gdb-proxy.ready')))
        launcher.chmod(0o755)
        renode_gdb_port = (args.renode_gdb_port if args.renode_gdb_port is not None
                           else args.gdb_port + 1)
        if not 1 <= args.gdb_port <= 65535:
            sys.exit('--gdb-port must be between 1 and 65535')
        if not 1 <= renode_gdb_port <= 65535:
            sys.exit('--renode-gdb-port must be between 1 and 65535')
        if renode_gdb_port == args.gdb_port:
            sys.exit('--gdb-port and --renode-gdb-port must differ')

        # The proxy turns ChibiOS registry entries into GDB threads and passes
        # all other packets through to Renode. Renode starts the machine when
        # the proxy establishes the upstream debugger connection.
        if args.reverse_debug:
            # Per-peripheral log levels trigger a Renode 1.16.1 logger bug
            # when restoring snapshots. The generated script omits those
            # overrides for GDB, so use one global level to keep output useful.
            commands.append('logLevel 3')
            reverse_command = 'reverseExecMode true'
            if args.reverse_gdb_limit:
                reverse_command += ' %u' % args.reverse_gdb_limit
            commands.append(reverse_command)
        commands.append('machine StartGdbServer %d' % renode_gdb_port)
        proxy_ready = outdir / 'gdb-proxy.ready'
        try:
            proxy_ready.unlink()
        except FileNotFoundError:
            pass
        gdb_proxy_proc = subprocess.Popen([
            sys.executable, str(root / 'Tools' / 'renode' / 'chibios_gdb.py'),
            '--listen', str(args.gdb_port),
            '--upstream', str(renode_gdb_port),
            '--elf', str(elf),
            '--ready-file', str(proxy_ready),
        ])
        term = None if args.no_xterm else find_terminal()
        if term is None:
            print('run this in another window to attach:\n    %s' % launcher)
        else:
            gdb_proc = subprocess.Popen(
                [term, '-title', 'gdb %s' % args.board, '-e', str(launcher)])
            print('gdb attaching in %s; release builds inline heavily, so '
                  'prefer a --debug firmware' % os.path.basename(term))
        features = 'ChibiOS thread debugging'
        if args.reverse_debug:
            features += ' and reverse debugging (%s history)' % (
                'unlimited' if args.reverse_gdb_limit == 0 else
                '%u instructions' % args.reverse_gdb_limit
            )
        print('%s enabled; execution starts under GDB control' % features)
    else:
        commands.append('start')
    commands += args.extra

    # a source-built renode launcher needs dotnet; the standard
    # user-local install location works without any global setup
    env = dict(os.environ)
    dotnet = Path.home() / '.dotnet'
    if not shutil.which('dotnet') and (dotnet / 'dotnet').exists():
        env['PATH'] = '%s:%s' % (dotnet, env.get('PATH', ''))

    print('ELF:     %s' % elf)
    print('renode:  %s' % renode)
    print('state:   %s' % state_dir)
    if generated['serial'] is None:
        print('serial:  no hardware UART in SERIAL_ORDER')
    else:
        print('serial:  SERIAL%s/%s on tcp:localhost:%u' %
              (generated['serial_index'], generated['serial'], args.uart_port))
    print('time:    %s' % ('unthrottled' if args.unthrottled else 'paced at 1x'))
    if args.can:
        print('CAN:     %s' % ', '.join(
            '%s=mcast:%u' % (bus, index)
            for index, bus in enumerate(generated['can_buses'])))
    if args.ethernet_tap:
        print('ethernet: host TAP %s' % args.ethernet_tap)
    if args.reproduce_pr33933:
        print('PR33933: expecting %s behavior' % args.reproduce_pr33933)
    cmd = [renode, '--disable-xwt'] + monitor + ['-e', '; '.join(commands)]
    try:
        ret = subprocess.run(cmd, env=env).returncode
    finally:
        if gdb_proc is not None:
            gdb_proc.terminate()
        if gdb_proxy_proc is not None:
            gdb_proxy_proc.terminate()
            try:
                (outdir / 'gdb-proxy.ready').unlink()
            except FileNotFoundError:
                pass
    return ret


if __name__ == '__main__':
    sys.exit(main())
