def hwdef_value(hwdef_h, name):
    '''integer value of a #define in a generated hwdef.h, or None'''
    try:
        for line in open(hwdef_h):
            parts = line.split()
            if len(parts) >= 3 and parts[0] == '#define' and parts[1] == name:
                try:
                    return int(parts[2], 0)
                except ValueError:
                    return None
    except OSError:
        pass
    return None


def storage_region(hwdef_h):
    '''(base, size) of the AP_FlashStorage sectors, which must read 0xFF.
       AP_FlashStorage always uses two sectors starting at
       STORAGE_FLASH_PAGE; the sector map is per MCU family.'''
    page = hwdef_value(hwdef_h, 'STORAGE_FLASH_PAGE')
    if page is None:
        return None
    text = open(hwdef_h).read() if os.path.exists(hwdef_h) else ''
    if 'STM32H7' in text:
        sectors = [128 * 1024] * 16          # uniform on the H743
    elif 'STM32G4' in text:
        sectors = [2 * 1024] * 256           # uniform on the G474
    elif 'STM32L4' in text:
        sectors = [2 * 1024] * 512           # uniform on L431/L476/L496
    elif 'STM32F103' in text:
        sectors = [1 * 1024] * 128           # uniform on medium-density F103
    elif 'STM32F105' in text:
        sectors = [2 * 1024] * 128           # uniform on connectivity-line F105
    elif 'STM32F3' in text:
        sectors = [2 * 1024] * 128           # uniform on the F303xC
    elif 'STM32F7' in text:
        # F765/F767 flight-controller hwdefs use the 2 MiB dual-bank layout.
        bank = [16 * 1024] * 4 + [64 * 1024] + [128 * 1024] * 7
        sectors = bank + bank
    elif 'STM32F4' in text:
        sectors = [16 * 1024] * 4 + [64 * 1024] + [128 * 1024] * 7
    else:
        return None
    if page + 1 >= len(sectors):
        return None
    base = 0x08000000 + sum(sectors[:page])
    return base, sectors[page] + sectors[page + 1]


def make_erased(path, size):
    '''Create a persistent erased image without replacing existing state.'''
    if path.exists():
        if path.stat().st_size != size:
            sys.exit('%s is %u bytes; expected %u (move it aside to reinitialize)' %
                     (path, path.stat().st_size, size))
        return path
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, 'wb') as f:
        f.write(b'\xff' * size)
    return path


def make_mcu_id(path):
    '''Return a persistent, randomly generated 96-bit STM32 unique ID.'''
    try:
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    except FileExistsError:
        pass
    except OSError as error:
        sys.exit('failed to create MCU ID %s: %s' % (path, error))
    else:
        try:
            with os.fdopen(fd, 'w') as mcu_id_file:
                mcu_id_file.write(secrets.token_hex(12) + '\n')
        except OSError as error:
            sys.exit('failed to write MCU ID %s: %s' % (path, error))

    try:
        text = path.read_text().strip()
        mcu_id = bytes.fromhex(text)
    except (OSError, ValueError) as error:
        sys.exit('invalid MCU ID in %s: %s' % (path, error))
    if len(mcu_id) != 12 or len(text) != 24:
        sys.exit('%s must contain exactly 24 hexadecimal characters' % path)
    return mcu_id


def make_flash_image(path, size, legacy_regions):
    '''Create full internal flash, importing the old region images once.'''
    if path.exists():
        if path.stat().st_size != size:
            sys.exit('%s is %u bytes; expected %u for this board '
                     '(move it aside to reinitialize)' %
                     (path, path.stat().st_size, size))
        return path

    contents = bytearray(b'\xff' * size)
    migrated = []
    for legacy_path, address, expected_size in legacy_regions:
        if not legacy_path.exists():
            continue
        legacy_size = legacy_path.stat().st_size
        if expected_size is not None and legacy_size != expected_size:
            sys.exit('%s is %u bytes; expected %u '
                     '(move it aside to skip migration)' %
                     (legacy_path, legacy_size, expected_size))
        offset = address - 0x08000000
        if legacy_size == 0 or offset < 0 or offset + legacy_size > size:
            sys.exit('%s does not fit in the %u-byte internal flash '
                     '(move it aside to skip migration)' % (legacy_path, size))
        with open(legacy_path, 'rb') as legacy:
            contents[offset:offset + legacy_size] = legacy.read()
        migrated.append((legacy_path, address))

    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, 'wb') as flash:
        flash.write(contents)
    for legacy_path, address in migrated:
        print('migrated %s to %s at 0x%08X; retained the old image' %
              (legacy_path, path, address))
    return path


def overlay_flash_image(flash_path, firmware_path, offset):
    '''Update the executable portion of a complete flash image.'''
    with open(flash_path, 'r+b') as flash, open(firmware_path, 'rb') as firmware:
        flash.seek(offset)
        shutil.copyfileobj(firmware, flash)


def prepare_iomcu_flash(path, bootloader, firmware, firmware_size,
                        force_update):
    '''Create or update the persistent 64 KiB IOMCU flash image.'''
    new_image = not path.exists()
    make_erased(path, IOMCU_FLASH_SIZE)
    if bootloader.stat().st_size > IOMCU_APP_OFFSET:
        sys.exit('%s does not fit in the IOMCU bootloader region' % bootloader)
    if firmware.stat().st_size > firmware_size:
        sys.exit('%s is larger than the 0x%X-byte IOMCU application region' %
                 (firmware, firmware_size))

    overlay_flash_image(path, bootloader, 0)
    if force_update:
        with path.open('r+b') as image:
            image.seek(IOMCU_APP_OFFSET)
            image.write(b'\xff' * firmware_size)
    elif new_image:
        overlay_flash_image(path, firmware, IOMCU_APP_OFFSET)
    return path


def make_fat_image(path, size, fat_bits=32, sectors_per_cluster=None):
    '''Create a persistent FAT image without replacing existing state.'''
    try:
        return fat_image.create_image(
            path, size, fat_bits=fat_bits,
            sectors_per_cluster=sectors_per_cluster)
    except (OSError, RuntimeError, ValueError) as error:
        sys.exit(str(error))


def make_persistence_repl(path, regions):
    '''Generate helpers which save mapped-memory regions on pause/exit.'''
    lines = [
        '// GENERATED by Tools/renode/run.py.',
        '// Persistent regions derived from the selected board hwdef.',
        '',
    ]
    for name, image, address, size in regions:
        lines += [
            '%s: Miscellaneous.AP_PersistentMemory @ none' % name,
            '    fileName: %s' % json.dumps(str(image)),
            '    address: 0x%08X' % address,
            '    size: 0x%X' % size,
            '',
        ]
    path.write_text('\n'.join(lines))
    return path


def has_debug_info(elf):
    '''True if the ELF carries DWARF. Without it gdb can only show
       addresses, so it is worth failing early rather than after two
       windows have opened.'''
    readelf = shutil.which('arm-none-eabi-readelf') or shutil.which('readelf')
    if readelf is None:
        return None
    try:
        out = subprocess.check_output([readelf, '-S', str(elf)],
                                      stderr=subprocess.DEVNULL).decode()
    except (OSError, subprocess.CalledProcessError):
        return None
    return '.debug_info' in out


def make_runtime_elf(source, destination):
    '''Copy an ELF without DWARF for Renode while GDB keeps the original.

       Reverse execution serializes Renode's ELF metadata into snapshots. A
       debug ArduPilot ELF carries tens of MiB of DWARF, so loading that copy
       into Renode makes the first snapshot unnecessarily large and slow.
       --strip-debug retains the normal symbol table used by Renode hooks.
    '''
    objcopy = shutil.which('arm-none-eabi-objcopy') or shutil.which('objcopy')
    if objcopy is None:
        sys.exit('objcopy is required for a GDB launch')
    try:
        subprocess.check_call(
            [objcopy, '--strip-debug', str(source), str(destination)],
            stderr=subprocess.STDOUT,
        )
    except (OSError, subprocess.CalledProcessError) as error:
        sys.exit('failed to make Renode runtime ELF: %s' % error)
    return destination


def wrap_binary_in_runtime_elf(source, destination, app_base):
    '''Wrap raw application bytes in a minimal ARM ELF for Renode startup.'''
    try:
        firmware = Path(source).read_bytes()
        if len(firmware) < 8:
            raise ValueError('firmware is too small to contain reset vectors')
        _stack_pointer, reset_vector = struct.unpack_from('<II', firmware)
        reset_address = reset_vector & ~1
        if not reset_vector & 1:
            raise ValueError('reset vector is not a Thumb address')
        if not app_base <= reset_address < app_base + len(firmware):
            raise ValueError(
                'reset vector 0x%08X is outside the application image' %
                reset_vector)

        data_offset = 0x100
        identifier = b'\x7fELF\x01\x01\x01' + b'\x00' * 9
        header = struct.pack(
            '<16sHHIIIIIHHHHHH',
            identifier, 2, 40, 1, reset_vector, 52, 0, 0x05000400,
            52, 32, 1, 0, 0, 0)
        program_header = struct.pack(
            '<IIIIIIII',
            1, data_offset, app_base, app_base,
            len(firmware), len(firmware), 7, 0x1000)
        with Path(destination).open('wb') as output:
            output.write(header)
            output.write(program_header)
            output.write(b'\x00' * (data_offset - output.tell()))
            output.write(firmware)
    except (OSError, ValueError) as error:
        sys.exit('failed to create runtime ELF for %s: %s' %
                 (source, error))
    return Path(destination)


def firmware_format(source):
    '''Return the supported firmware format, checking ELF contents.'''
    source = Path(source)
    try:
        with source.open('rb') as source_file:
            magic = source_file.read(4)
    except OSError as error:
        sys.exit('failed to read firmware %s: %s' % (source, error))
    if magic == b'\x7fELF':
        return 'elf'
    suffix = source.suffix.lower()
    if suffix in ('.apj', '.bin', '.hex'):
        return suffix[1:]
    if suffix == '.elf':
        sys.exit('%s has an .elf suffix but is not an ELF file' % source)
    sys.exit('unsupported firmware format for %s '
             '(expected APJ, BIN, HEX, or ELF)' % source)


def _decode_apj(source, maximum_size, expected_board_id):
    try:
        descriptor = json.loads(source.read_text())
        if not isinstance(descriptor, dict):
            raise ValueError('APJ descriptor is not a JSON object')
        if descriptor.get('magic') != 'APJFWv1':
            raise ValueError('invalid APJ magic')
        board_id = int(descriptor['board_id'])
        if expected_board_id is not None and board_id != expected_board_id:
            raise ValueError(
                'APJ board ID %u does not match target board ID %u' %
                (board_id, expected_board_id))
        compressed = base64.b64decode(descriptor['image'], validate=True)
        decompressor = zlib.decompressobj()
        firmware = decompressor.decompress(compressed, maximum_size + 1)
        if len(firmware) > maximum_size or not decompressor.eof:
            raise ValueError('expanded APJ image exceeds target flash')
        if decompressor.unused_data:
            raise ValueError('APJ image has trailing compressed data')
        image_size = int(descriptor['image_size'])
        if image_size != len(firmware):
            raise ValueError(
                'APJ image_size is %u but image contains %u bytes' %
                (image_size, len(firmware)))
        return firmware
    except (KeyError, OSError, TypeError, ValueError,
            binascii.Error, zlib.error) as error:
        sys.exit('failed to decode firmware %s: %s' % (source, error))


def make_firmware_binary(source, destination, app_base, flash_size,
                         expected_board_id=None):
    '''Convert an APJ, BIN, HEX, or ELF firmware to a flash overlay.'''
    source = Path(source)
    destination = Path(destination)
    image_format = firmware_format(source)
    if image_format == 'bin':
        try:
            shutil.copyfile(source, destination)
        except OSError as error:
            sys.exit('failed to copy firmware %s: %s' % (source, error))
        return destination
    if image_format == 'apj':
        application_size = 0x08000000 + flash_size - app_base
        destination.write_bytes(
            _decode_apj(source, application_size, expected_board_id))
        return destination
    if image_format == 'hex':
        try:
            from intelhex import IntelHex
            from intelhex import IntelHexError
        except ImportError:
            sys.exit('the intelhex Python module is required for %s' % source)
        try:
            image = IntelHex(str(source))
            if len(image) == 0:
                sys.exit('firmware contains no data: %s' % source)
            end = image.maxaddr()
            if not any(segment_end > app_base
                       for _segment_start, segment_end in image.segments()):
                sys.exit('%s contains no data at application address '
                         '0x%08X or above' % (source, app_base))
            if end >= 0x08000000 + flash_size:
                sys.exit('%s ends at 0x%08X, beyond target flash' %
                         (source, end))
            image.padding = 0xff
            image.tobinfile(
                str(destination), start=app_base, end=end)
        except (OSError, IntelHexError) as error:
            sys.exit('failed to convert firmware %s: %s' % (source, error))
        return destination

    # Extract file-backed flash contents, preserving erased ELF gaps.
    objcopy = shutil.which('arm-none-eabi-objcopy') or shutil.which('objcopy')
    if objcopy is None:
        sys.exit('objcopy is required to make the Renode flash overlay')
    try:
        subprocess.check_call(
            [objcopy, '-O', 'binary', '--gap-fill=0xff',
             str(source), str(destination)],
            stderr=subprocess.STDOUT,
        )
    except (OSError, subprocess.CalledProcessError) as error:
        sys.exit('failed to make Renode flash overlay: %s' % error)
    return destination


def make_bootloader_binary(source, destination):
    '''Convert an ELF, raw BIN, or Intel HEX bootloader to a flash overlay.'''
    try:
        with source.open('rb') as source_file:
            magic = source_file.read(4)
    except OSError as error:
        sys.exit('failed to read bootloader %s: %s' % (source, error))

    suffix = source.suffix.lower()
    if magic == b'\x7fELF' or suffix == '.elf':
        return make_firmware_binary(source, destination), 0x08000000
    if suffix == '.bin':
        try:
            shutil.copyfile(source, destination)
        except OSError as error:
            sys.exit('failed to copy bootloader %s: %s' % (source, error))
        return destination, 0x08000000
    if suffix in ('.hex', '.ihex'):
        try:
            from intelhex import IntelHex
            from intelhex import IntelHexError
        except ImportError:
            sys.exit('the intelhex Python module is required for %s' % source)
        try:
            image = IntelHex(str(source))
            if len(image) == 0:
                sys.exit('bootloader contains no data: %s' % source)
            start = image.minaddr()
            image.padding = 0xff
            image.tobinfile(str(destination), start=start, end=image.maxaddr())
        except (OSError, IntelHexError) as error:
            sys.exit('failed to convert bootloader %s: %s' % (source, error))
        return destination, start
    sys.exit('unsupported bootloader format for %s (expected ELF, BIN, or HEX)' %
             source)


def find_terminal():
    for term in ('xterm', 'x-terminal-emulator', 'konsole', 'gnome-terminal'):
        path = shutil.which(term)
        if path:
            return path
    return None


def find_renode(explicit, here):
    if explicit:
        return explicit
    env = os.environ.get('RENODE')
    if env:
        return env
    # gitignored symlink next to this script: the way to pin a local
    # (ideally patched) build without any environment setup
    local = here / 'renode'
    if local.exists():
        return str(local)
    path = shutil.which('renode')
    if path:
        return path
    for candidate in ('/opt/renode/renode', '/usr/local/bin/renode'):
        if Path(candidate).exists():
            return candidate
    sys.exit("no renode found: pass --renode, set $RENODE, put renode on\n"
             "PATH, or symlink your build here:\n"
             "  ln -s /path/to/renode %s" % local)


def process_tree(root_pid):
    '''Return live process IDs rooted at root_pid from Linux procfs.'''
    pending = [root_pid]
    processes = set()
    while pending:
        pid = pending.pop()
        if pid in processes:
            continue
        task_dir = Path('/proc') / str(pid) / 'task'
        try:
            tasks = list(task_dir.iterdir())
        except FileNotFoundError:
            continue
        processes.add(pid)
        for task in tasks:
            try:
                children = (task / 'children').read_text().split()
            except FileNotFoundError:
                continue
            pending.extend(int(child) for child in children)
    return processes


def renode_cpu_threads(root_pid):
    '''Find Renode's emulated ArduPilot CPU threads below its launcher.'''
    threads = set()
    for pid in process_tree(root_pid):
        task_dir = Path('/proc') / str(pid) / 'task'
        try:
            tasks = list(task_dir.iterdir())
        except FileNotFoundError:
            continue
        for task in tasks:
            try:
                name = (task / 'comm').read_text().strip()
            except FileNotFoundError:
                continue
            # Linux truncates comm to 15 characters. The complete Renode name
            # is ardupilot.cpu[0], so match the stable part of that name.
            if name.startswith('ardupilot.cpu['):
                threads.add(int(task.name))
    return threads


def stop_renode_process(process):
    if process.poll() is not None:
        return
    if os.name == 'posix':
        os.killpg(process.pid, signal.SIGTERM)
    else:
        process.terminate()
    try:
        process.wait(timeout=5)
    except subprocess.TimeoutExpired:
        if os.name == 'posix':
            os.killpg(process.pid, signal.SIGKILL)
        else:
            process.kill()
        process.wait()


def run_renode(cmd, env, cpusel):
    '''Run Renode, optionally pinning only its emulated CPU thread.'''
    process = subprocess.Popen(
        cmd, env=env, start_new_session=(os.name == 'posix'))
    pinned = set()
    try:
        if cpusel is None:
            return process.wait()
        while process.poll() is None:
            live_threads = renode_cpu_threads(process.pid)
            pinned.intersection_update(live_threads)
            for thread_id in sorted(live_threads - pinned):
                try:
                    os.sched_setaffinity(thread_id, {cpusel})
                except ProcessLookupError:
                    continue
                pinned.add(thread_id)
                print('pinned Renode emulation thread %u to host CPU %u' %
                      (thread_id, cpusel))
            time.sleep(0.05 if not pinned else 0.5)
        return process.returncode
    except BaseException:
        stop_renode_process(process)
        raise


