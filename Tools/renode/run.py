#!/usr/bin/env python3
'''
Launch an ArduPilot board under Renode, in the style of the AM32
harness's gen_target.py --run:

    Tools/renode/run.py <board>

drops into an interactive Renode monitor with the firmware running and
the first hardware UART on tcp:localhost:5762. Select a different
SERIAL_ORDER entry with --serial. The socket terminal serves its first
client only, so restart to reconnect.

Persistent media defaults to renode/<board>/ at the repository root. Use
--state-dir to select an exact alternative directory.

Renode is found from --renode, $RENODE, or PATH, in that order. The
performance patches in patches/ matter (roughly 4x): point --renode at
a build of renode v1.16.1 with them applied (see the README).
'''

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

import gen_board

