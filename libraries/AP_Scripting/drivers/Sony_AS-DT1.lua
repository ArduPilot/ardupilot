-- ---------- send command (16-byte padding + CR + 16-byte flush) ----------
local function send_cmd(s)
  if not port then return end
  local total = string.len(s) + 1
  local pad = (16 - (total % 16)) % 16
  local out = s .. string.rep(" ", pad) .. "\r" .. string.rep(" ", 15) .. "\r"
  for i = 1, string.len(out) do port:write(string.byte(out, i)) end
end

local function drain()
  if not port then return end
  -- flush buffer: readstring reads in chunks (fast, C-side)
  local s = port:readstring(4096)
  while s ~= nil and string.len(s) > 0 do s = port:readstring(4096) end
end

local function read_vbuf()
  if not port then return end
  local s = port:readstring(READ_CAP)
  if s ~= nil and string.len(s) > 0 then vbuf = vbuf .. s end
  if string.len(vbuf) > 3000 then vbuf = string.sub(vbuf, -1500) end
end

local function ensure_backend()
  if not backend then backend = proximity:get_backend(0) end
  local mn, mx = P_MIN_M:get(), P_MAX_M:get()
  if backend and mn and mx then
    backend:set_distance_min_max(mn, mx)
  end
end

-- ---------- 3D path ----------
local function reset_cmin()
  for c = 1, NCELLS do cmin[c] = CMINBIG end
end

local function acc3d(p, z)
  if z >= MIN_RAW and z <= MAX_RAW then
    local c = CELL_OF[p + 1]
    if z < cmin[c] then cmin[c] = z end
  end
end

local function finalize3d()
  frames = frames + 1
  ensure_backend()
  local last, cnt, nearest = 0, 0, CMINBIG
  for c = 1, NCELLS do
    if cmin[c] < CMINBIG then last = c; cnt = cnt + 1
      if cmin[c] < nearest then nearest = cmin[c] end
    end
  end
  if backend then
    for c = 1, NCELLS do
      if cmin[c] < CMINBIG then
        local zm = cmin[c] * 0.00025           -- *0.25mm/1000 = m (forward Z)
        local v = Vector3f()
        v:x(zm)
        v:y(zm * CELL_KY[c])
        v:z(zm * CELL_KZ[c])
        backend:handle_script_3d_msg(v, c == last)  -- last valid -> update boundary
      end
    end
  end
  if DEBUG and frames % 20 == 0 then
    if backend then
      local nm = (nearest < CMINBIG) and (nearest * 0.00025) or -1
      gcs:send_text(6, string.format("AS-DT1[3D]: %d cells, nearest %.2f m", cnt, nm))
    else
      gcs:send_text(4, "AS-DT1: parsing OK but no proximity backend (PRX1_TYPE=15 + reboot?)")
    end
  end
end

-- ---------- 2D path ----------
local function reset_smin()
  for s = 1, NSECT do smin[s] = CMINBIG end
end

