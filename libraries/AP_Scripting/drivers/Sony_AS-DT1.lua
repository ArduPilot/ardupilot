local PARAM_TABLE_KEY    = 97      -- must be unique across all scripts on the autopilot
local PARAM_TABLE_PREFIX = "ASDT1_"
assert(param:add_table(PARAM_TABLE_KEY, PARAM_TABLE_PREFIX, 8), "ASDT1: could not add param table")

-- bind a parameter to a variable
local function bind_param(name)
  local p = Parameter()
  assert(p:init(name), string.format("ASDT1: could not find %s parameter", name))
  return p
end

-- add a parameter and bind it to a variable
local function bind_add_param(name, idx, default_value)
  assert(param:add_param(PARAM_TABLE_KEY, idx, name, default_value),
         string.format("ASDT1: could not add param %s", name))
  return bind_param(PARAM_TABLE_PREFIX .. name)
end

