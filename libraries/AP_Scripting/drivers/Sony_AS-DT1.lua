--[[
  Sony AS-DT1 LiDAR depth sensor -> ArduPilot proximity driver (PRX1_TYPE = 15)

  The AS-DT1 is a compact dToF LiDAR (29x29x31 mm, <50 g) with up to 576
  measurement points over a ~37 x 29 deg field of view and a range of about
  20 m outdoors / 40 m indoors. Out of the box the sensor outputs its data
  over its USB-C port: connect it to a PC once and use Sony's AS-DT1 sample
  application (from the SDK) to switch it to UART output on the 8-pin
  connector at 460800 baud (the driver default, see ASDT1_BAUD). Power it
  from 12-24 V (NOT the 5 V of a telemetry port); only TX, RX and GND go
  to the autopilot.

  Operating modes (ASDT1_MODE):
    2 = 2D  : the frame is collapsed into horizontal azimuth sectors and the
              per-sector minimum distance is pushed with pitch 0
              (handle_script_distance_msg). ArduPilot streams the result as
              MAVLink DISTANCE_SENSOR.
    4 = 2D+ : like 2D, but the vertical band that is kept follows the true
              horizon using the AHRS pitch, so a nose-down attitude in
              forward flight does not turn the ground into an obstacle.
    3 = 3D  : full 3D obstacle points are pushed (handle_script_3d_msg).

  Setup: SCR_ENABLE = 1, SCR_VM_I_COUNT = 50000, SERIALx_PROTOCOL = 28 on
  the sensor port, PRX1_TYPE = 15, reboot, copy this script to APM/scripts
  and reboot again. See Sony_AS-DT1.md for details.

  The lookup tables below (stream order and per-point ray directions,
  grid 5x5 for 3D, 9 sectors for 2D, 10 Hz) are generated from
  the measurement-point order documented in the AS-DT1 API manual and the
  ray geometry reported by the sensor's 'svminfo' command. They are
  generated by gen_asdt1_lua.py (UAV-DEV GmbH); do not edit them by hand.
--]]

