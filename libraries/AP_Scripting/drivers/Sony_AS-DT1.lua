-- i.e. the rows that look along the airframe-forward / true-horizon direction. With a level
-- mount and plain 2D, pitch10 = 0 -> just |elevation| <= BAND.
local function acc2d(p, z)
  if z >= MIN_RAW and z <= MAX_RAW then
    local ew = PT_EL10[p + 1] + pitch10
    if ew < 0 then ew = -ew end
    if ew <= BAND10 then
      local s = SECT_OF[p + 1]
      if z < smin[s] then smin[s] = z end
    end
  end
end

local function finalize2d()
  frames = frames + 1
  ensure_backend()
  local last, cnt, nearest = 0, 0, CMINBIG
  for s = 1, NSECT do
    if smin[s] < CMINBIG then last = s; cnt = cnt + 1
      if smin[s] < nearest then nearest = smin[s] end
    end
  end
  if backend then
    for s = 1, NSECT do
      if smin[s] < CMINBIG then
        -- forward-Z [raw] -> horizontal distance [m]: Z_m / cos(az)
        local hd = smin[s] * 0.00025 * SECT_INVCOS[s]
        backend:handle_script_distance_msg(hd, SECT_YAW[s], 0.0, s == last)
      end
    end
  end
  if DEBUG and frames % 20 == 0 then
    if backend then
      local nm = (nearest < CMINBIG) and (nearest * 0.00025) or -1
      gcs:send_text(6, string.format("AS-DT1[%s]: %d sectors, nearest %.2f m (MAVLink DISTANCE_SENSOR)", LBL2D, cnt, nm))
    else
      gcs:send_text(4, "AS-DT1: parsing OK but no proximity backend (PRX1_TYPE=15 + reboot?)")
    end
  end
end

-- ---------- bind the active mode once ----------
if MODE == "3d" then
  acc, finalize, reset_acc = acc3d, finalize3d, reset_cmin
else                        -- "2d" and "2dp" share acc2d (differ only in pitch10)
  acc, finalize, reset_acc = acc2d, finalize2d, reset_smin
end

local function process(b)
  if in_pl then
    gi = gi + 1
    if gi == 1 then g1 = b
    elseif gi == 2 then g2 = b
    elseif gi == 3 then g3 = b
    elseif gi == 4 then g4 = b
    else
      g5 = b; gi = 0
      local z0 = (g1 << 12) | (g2 << 4) | (g3 >> 4)
      local z1 = ((g3 & 0x0F) << 16) | (g4 << 8) | g5
      acc(pidx, z0); acc(pidx + 1, z1)
      pidx = pidx + 2
      if pidx >= NPOINTS then
        finalize(); in_pl = false; st_sync = 0
      end
    end
  else
    if b == string.byte(MARK, st_sync + 1) then
      st_sync = st_sync + 1
      if st_sync == MARKLEN then
        in_pl = true; gi = 0; pidx = 0; st_sync = 0
        refresh_params(); reset_acc()   -- pick up live ASDT1_* changes for this frame
      end
    elseif b == string.byte(MARK, 1) then
      st_sync = 1
    else
      st_sync = 0
    end
  end
end

local function run_read()
  if not port then return end
  -- batch read as string (1 C call instead of hundreds of read()) -> stays within
  -- the instruction limit (SCR_VM_I_COUNT).
  local s = port:readstring(READ_CAP)
  if s == nil then return end
  for i = 1, string.len(s) do process(string.byte(s, i)) end
end

-- ---------- main loop ----------
local function update()
  if not port then
    if DEBUG then gcs:send_text(3, "AS-DT1: no scripting serial (SERIALx_PROTOCOL=28? ASDT1_SP?)") end
    return update, 3000
  end

  if phase == PH_INIT then
    port:begin(math.floor(P_BAUD:get() + 0.5))
    port:set_flow_control(0)
    drain(); vbuf = ""; tries = 0
    send_cmd("ver"); timer = math.floor(300 / UPDATE_MS); phase = PH_VER

  elseif phase == PH_VER then
    read_vbuf()
    if string.find(vbuf, "dToF", 1, true) then
      if DEBUG then gcs:send_text(6, "AS-DT1: sync ok") end
      drain(); send_cmd("format binz"); timer = math.floor(250 / UPDATE_MS); phase = PH_FMT
    else
      timer = timer - 1
      if timer <= 0 then
        tries = tries + 1
        if tries > 60 then
          if DEBUG then gcs:send_text(3, "AS-DT1: resync failed") end
          phase = PH_INIT; return update, 2000
        end
        port:write(0x20)                 -- 1 space: shift alignment
        vbuf = ""; send_cmd("ver"); timer = math.floor(250 / UPDATE_MS)
      end
    end

  elseif phase == PH_FMT then
    timer = timer - 1
    if timer <= 0 then
      drain(); send_cmd("fsync " .. FSYNC_MS); timer = math.floor(250 / UPDATE_MS); phase = PH_FSY
    end

  elseif phase == PH_FSY then
    timer = timer - 1
    if timer <= 0 then
      drain(); reset_acc(); in_pl = false; st_sync = 0; pidx = 0; gi = 0
      ensure_backend()
      phase = PH_RUN
      if DEBUG then
        if MODE == "3d" then
          gcs:send_text(6, string.format("AS-DT1: streaming @ %d Hz, 3D %dx%d",
                        math.floor(1000 / FSYNC_MS), NX, NY))
        else
          gcs:send_text(6, string.format("AS-DT1: streaming @ %d Hz, %s %d sectors, band +/-%d deg -> MAVLink",
                        math.floor(1000 / FSYNC_MS), LBL2D, NSECT, math.floor(BAND10 / 10)))
        end
      end
    end

  else
    run_read()
  end

  return update, UPDATE_MS
end

-- wrapper around update(): a runtime error is reported to the GCS instead of
-- stopping the script, and the loop is retried after 1 s
local function protected_wrapper()
  local ok, fn_or_err, delay = pcall(update)
  if not ok then
    gcs:send_text(3, "AS-DT1: internal error: " .. tostring(fn_or_err))
    return protected_wrapper, 1000
  end
  return protected_wrapper, delay or UPDATE_MS
end

return protected_wrapper, 2000
