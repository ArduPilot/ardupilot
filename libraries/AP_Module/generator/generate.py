"""Generate firmware and native clients for the experimental host-call ABI."""

import argparse
import hashlib
import json
import os
import re
import tempfile

from pathlib import Path

import ada_bindings
import bindings
import contracts
import cpp_bindings
import fortran_bindings
import language_coverage

from native_templates import render

ROOT = Path(__file__).resolve().parents[1]
TYPES = {
    'void': ('void', '()'), 'u8': ('uint8_t', 'u8'), 'u32': ('uint32_t', 'u32'),
    'i32': ('int32_t', 'i32'), 'u64': ('uint64_t', 'u64'),
    'pointer': ('void *', '*mut core::ffi::c_void'),
    'const_bytes': ('const uint8_t *', '*const u8'), 'mut_bytes': ('uint8_t *', '*mut u8'),
}
# Changing the generated header prefix/layout must change this salt.
LAYOUT = 'AP_Module.HostApi.v1:u32_version,u32_size,u8_fingerprint[16],ordered_function_pointers'


def identifier(name):
    if not isinstance(name, str) or not re.fullmatch('[A-Za-z_][A-Za-z0-9_]*', name):
        raise ValueError('invalid identifier')
    return name


def generate(spec, binding_spec=None):
    if binding_spec is None:
        binding_spec = bindings.specification()
    if type(spec['version']) is not int or not 0 < spec['version'] <= 0xFFFFFFFF:
        raise ValueError('invalid ABI version')
    names = set()
    for function in spec['functions']:
        name = identifier(function['name'])
        if name in names or name in ('version', 'size', 'fingerprint'):
            raise ValueError('duplicate or reserved function name')
        names.add(name)
        if function['return'] not in TYPES or function['args'][:1] != [['context', 'pointer']]:
            raise ValueError('invalid host function')
        arguments = set()
        for name, kind in function['args']:
            identifier(name)
            if name in arguments or kind not in TYPES or kind == 'void':
                raise ValueError('invalid argument')
            arguments.add(name)
    # This identity is the frozen core C ABI, never the binding catalogue.
    required = spec['required_functions']
    if type(required) is not int or not 0 < required <= len(spec['functions']):
        raise ValueError('invalid core ABI prefix')
    identity = dict(host=dict(spec, functions=spec['functions'][:required]))
    canonical = LAYOUT.encode() + b'\n' + json.dumps(identity, sort_keys=True, separators=(',', ':')).encode()
    fingerprint = hashlib.sha256(canonical).digest()[:16]
    fingerprint_values = ', '.join(f'0x{byte:02x}' for byte in fingerprint)
    notice = '// SPDX-License-Identifier: GPL-3.0-or-later\n// Generated by generator/generate.py; do not edit.\n'
    cpp_status, rust_status = [], []
    for name, value in spec['status'].items():
        identifier(name)
        if type(value) is not int or not -(1 << 31) <= value < 1 << 31:
            raise ValueError('invalid status value')
        cpp_status.append(f'#define AP_MODULE_STATUS_{name} ({value})\n')
        rust_status.append(f'pub const STATUS_{name}: i32 = {value};\n')
    # Rust uses nullable function pointers so entry validation can reject an
    # incomplete host table without first constructing invalid Rust values.
    cpp_functions, rust_functions = [], []
    for function in spec['functions']:
        name, result = function['name'], function['return']
        c_args = ', '.join(f'{TYPES[kind][0]} {arg}' for arg, kind in function['args'])
        r_args = ', '.join(f'{arg}: {TYPES[kind][1]}' for arg, kind in function['args'])
        cpp_functions.append(f'    {TYPES[result][0]} (*{name})({c_args});\n')
        rust_functions.append(f'    pub {name}: Option<unsafe extern "C" fn({r_args}) -> {TYPES[result][1]}>,\n')
    offsets = [('version', '0'), ('size', '4'), ('fingerprint', '8')]
    offsets += [(f['name'], f'24 + {i} * sizeof(void *)') for i, f in enumerate(spec['functions'])]
    cpp_assertions = [f'AP_MODULE_LAYOUT_ASSERT(offsetof(AP_ModuleHostApi, {name}) == {offset}, "HostApi.{name} layout");\n'
                      for name, offset in offsets]
    cpp_assertions.append(
        f'AP_MODULE_LAYOUT_ASSERT(sizeof(AP_ModuleHostApi) == 24 + {len(names)} * sizeof(void *), "HostApi size");\n')
    rust_assertions = []
    for name, offset in offsets:
        offset = offset.replace('sizeof(void *)', 'core::mem::size_of::<*const ()>()')
        rust_assertions.append(f'    assert!(core::mem::offset_of!(HostApi, {name}) == {offset});\n')
    rust_assertions.append(
        f'    assert!(core::mem::size_of::<HostApi>() == 24 + {len(names)} * core::mem::size_of::<*const ()>());\n')
    cpp = render(
        'host_cpp/host_api.h', notice=notice, version=spec['version'], fingerprint=fingerprint_values,
        statuses=''.join(cpp_status), functions=''.join(cpp_functions), assertions=''.join(cpp_assertions),
    )
    rust = render(
        'rust/host_api.rs', notice=notice, version=spec['version'], fingerprint=fingerprint_values,
        statuses=''.join(rust_status), functions=''.join(rust_functions), assertions=''.join(rust_assertions),
        required_functions=''.join(f'            && self.{f["name"]}.is_some()\n' for f in spec['functions']),
    )
    contract = dict(abi_version=spec['version'], fingerprint=fingerprint.hex())
    outputs = {'HostApi.h': cpp, 'sdk/rust/src/api.rs': rust,
               'sdk/abi.json': json.dumps(contract, indent=2) + '\n'}
    outputs.update(cpp_bindings.emit(binding_spec, notice))
    outputs.update(ada_bindings.emit(binding_spec, spec))
    outputs.update(fortran_bindings.emit(binding_spec, spec))
    outputs.update(bindings.emit(binding_spec))
    outputs.update(contracts.emit(binding_spec, notice))
    binding_names = contracts.binding_names(binding_spec)
    for name, content in outputs.items():
        if name.endswith('.rs'):
            content = re.sub(
                r'crate::imports::BINDING_(\d+)',
                lambda match: 'crate::imports::BINDING_' + binding_names[int(match.group(1))].upper(),
                content,
            )
        outputs[name] = content
    outputs['generator/coverage.json'] = json.dumps(language_coverage.report(binding_spec, outputs), indent=2) + '\n'
    return outputs


def write_outputs(outputs, output_dir, check=False):
    for name, content in outputs.items():
        path = output_dir / name
        if check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'stale generated file: {path}')
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        if path.exists() and path.read_text() == content:
            continue
        with tempfile.NamedTemporaryFile('w', dir=path.parent, delete=False) as temporary:
            temporary.write(content)
            temporary_path = Path(temporary.name)
        os.replace(temporary_path, path)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path, required=True,
                        help='write generated files below this build directory')
    parser.add_argument('--check', action='store_true', help='fail if files in --output-dir differ')
    parser.add_argument('--check-compatibility', type=Path, help='require contracts from an earlier imports.json catalogue')
    args = parser.parse_args()
    outputs = generate(json.loads((ROOT / 'generator/host_api.json').read_text()))
    if args.check_compatibility:
        contracts.check_compatibility(json.loads(args.check_compatibility.read_text()),
                                      json.loads(outputs['generator/imports.json']))
    write_outputs(outputs, args.output_dir, args.check)


if __name__ == '__main__':
    main()
