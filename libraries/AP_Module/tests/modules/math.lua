-- Same fixed operation sequence and tolerances as math.rs.
local function vector(x, y, z)
    local v = Vector3f()
    v:x(x); v:y(y); v:z(z)
    return v
end
local function near(a, b)
    assert(math.abs(a - b) < 0.00001)
end
local function same(v, x, y, z)
    near(v:x(), x); near(v:y(), y); near(v:z(), z)
end
local x, z = vector(1, 0, 0), vector(0, 0, 1)
local half_pi = math.pi * 0.5
local v = vector(3, 4, 0)
assert(Vector3f():is_zero())
assert(not v:is_zero() and not v:is_nan() and not v:is_inf())
assert(vector(0, math.huge, 0):is_inf())
near(v:length(), 5)
near(v:dot(x), 3)
same(v:cross(z), 4, -3, 0)
same(v:scale(2), 6, 8, 0)
same((v + x) - x, 3, 4, 0)
near(v:angle(x), 0.9272952)
local rotated = v:copy()
rotated:rotate_xy(half_pi)
same(rotated, -4, 3, 0)
v:normalize()
same(v, 0.6, 0.8, 0)

local q = Quaternion()
near(q:q1(), 1); near(q:q2(), 0); near(q:q3(), 0); near(q:q4(), 0)
q:from_axis_angle(z, half_pi)
near(q:length(), 1)
near(q:get_euler_roll(), 0); near(q:get_euler_pitch(), 0); near(q:get_euler_yaw(), half_pi)
q:normalize()
local axis = vector(99, 99, 99)
q:to_axis_angle(axis)
same(axis, 0, 0, half_pi)
local body = x:copy()
q:earth_to_body(body)
same(body, 0, 1, 0)
local identity = q * q:inverse()
near(identity:q1(), 1); near(identity:q2(), 0); near(identity:q3(), 0); near(identity:q4(), 0)
q:from_euler(0.1, -0.2, 0.3)
near(q:get_euler_roll(), 0.1); near(q:get_euler_pitch(), -0.2); near(q:get_euler_yaw(), 0.3)
q:from_angular_velocity(z, 0.02)
near(q:q4() / q:q1(), 0.01)
near(q:length(), 1)
