#!/usr/bin/env bash
# AP_FLAKE8_CLEAN  (not Python, but keep the marker as a reminder this is CI-visible)
set -euo pipefail

# ap_iram_sections.sh - generate a Zephyr linker fragment placing AP symbols in
# IRAM. Takes demangled C++ names from the per-board registry and resolves them
# to mangled ELF section names.

if [[ $# -ne 3 ]]; then
    echo "usage: $0 <buildroot> <registry_file> <out_ld>" >&2
    exit 2
fi

buildroot="$1"
registry="$2"
out_ld="$3"

tmpdir="$(mktemp -d)"
trap 'rm -rf "$tmpdir"' EXIT

raw_txt="$tmpdir/raw_symbols.txt"
map_txt="$tmpdir/mangled_map.txt"

# ── Step 1: collect all defined text symbols from the AP build artifacts ──────
find "$buildroot" -type f \( -name '*.a' -o -name '*.o' \) -print0 \
    | xargs -0 -r nm --defined-only 2>/dev/null \
  | awk '
      {
          n = NF
          if (n >= 3) {
              typ = $(n-1)
              sym = $n
              if (typ ~ /^[TtWw]$/ && sym !~ /^\./) print sym
          }
      }
  ' | sort -u > "$raw_txt"

# ── Step 2: build demangled→mangled map ──────────────────────────────────────
paste "$raw_txt" <(c++filt < "$raw_txt") \
  | awk '
      {
          raw = $1
          $1 = ""
          dem = $0
          sub(/^[[:space:]]+/, "", dem)
          sub(/\(.*/, "", dem)          # strip argument list
          gsub(/[[:space:]]+/, "", dem) # collapse whitespace
          if (dem != "") print dem "|" raw
      }
  ' > "$map_txt"

# ── Step 3: generate linker fragment ─────────────────────────────────────────
{
    echo "/* auto-generated by ap_iram_sections.sh from $(basename "$registry"); do not edit */"
    echo "  .iram0.ap_text : ALIGN(4)"
    echo "  {"

    # Extract the symbol column (field 2), strip comments and whitespace
    awk -F'|' '
        /^[[:space:]]*#/ { next }
        /^[[:space:]]*$/ { next }
        NF >= 2 {
            s = $2
            gsub(/#.*/, "", s)
            gsub(/^[[:space:]]+|[[:space:]]+$/, "", s)
            if (s != "") print s
        }
    ' "$registry" | sort -u | while IFS= read -r wanted; do
        norm="$(printf '%s' "$wanted" | sed 's/[[:space:]]//g')"
        awk -F'|' -v want="$norm" '
            $1 == want {
                raw = $2
                print "        *(.text." raw ")"
                print "        *(.text.hot." raw ")"
                print "        *(.text.startup." raw ")"
                print "        *(.text.unlikely." raw ")"
                print "        *(.gnu.linkonce.t." raw ")"
            }
        ' "$map_txt"
    done
    echo "  } > iram0_0_seg AT > FLASH"
} | awk '!seen[$0]++' > "$out_ld"

echo "ap_iram_sections: wrote $(grep -c '\.text\.' "$out_ld" || echo 0) section picks to $out_ld" >&2
