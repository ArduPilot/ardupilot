#if defined(CONFIG_SOC_SERIES_STM32H7X)
static void stm32h7_prime_usb_pwr(void)
{
        /* Prime VDDUSB/USBRDY path so UDC H7 power wait has valid state. */
        LL_PWR_EnableUSBVoltageDetector();
        LL_PWR_EnableUSBReg();
}

static void stm32h7_bootloader_style_usb_reinit(void)
{
        g_usb_phase = 151U;
        /* Zephyr's RCC init left D2CCIP2R at PLL1Q (240 MHz) and the bootloader's
         * AHB1ENR bit 27 was still set, so the OTG core took that pulse and wedged.
         * Hard-reset USB2 OTG via AHB1RSTR against the now-correct 48 MHz HSI48. */

        /* Disable ULPI clock (not used; we use the embedded FS PHY). */
        LL_AHB1_GRP1_DisableClock(LL_AHB1_GRP1_PERIPH_USB2OTGHSULPI);
        g_usb_phase = 152U;

        /* Quiesce: disable AHB1 clock for USB2 OTG before hardware reset. */
        LL_AHB1_GRP1_DisableClock(LL_AHB1_GRP1_PERIPH_USB2OTGHS);
        g_usb_phase = 153U;

        /* Issue hardware reset — clears all OTG core registers to power-on
         * defaults, removing any bad state from the 240 MHz PLL1Q transient. */
        LL_AHB1_GRP1_ForceReset(LL_AHB1_GRP1_PERIPH_USB2OTGHS);
        g_usb_phase = 154U;
        k_busy_wait(500U);  /* 500 µs — well above minimum reset pulse width */
        g_usb_phase = 155U;
        LL_AHB1_GRP1_ReleaseReset(LL_AHB1_GRP1_PERIPH_USB2OTGHS);
        g_usb_phase = 156U;
        for (volatile uint32_t i = 0U; i < 20000U; i++) {
                __NOP();
        }
        g_usb_phase = 157U;

        /* Re-enable AHB1 clock. OTG core now starts with D2CCIP2R = HSI48.
         * HAL_PCD_Init → USB_CoreInit will configure all registers and CSRST
         * should complete normally. No skip flags needed. */
        LL_AHB1_GRP1_EnableClock(LL_AHB1_GRP1_PERIPH_USB2OTGHS);
        g_usb_phase = 158U;

        g_usb_phase = 159U;
}

static void stm32h7_force_usb_clock_hsi48(void)
{
        /* CRITICAL: Force USB kernel clock to HSI48 (the bootloader had it there).
         * The Zephyr RCC initialization might leave it unset or at a bad value.
         * We use LL (low-level) functions to directly set USB clock selector.
         */
        LOG_INF("Configuring USB clock for HSI48");

        /* Capture D2CCIP2R before change */
        volatile uint32_t *d2ccip2r_reg = (volatile uint32_t *)0x580244A8U;
        g_usb_d2ccip2r_before_clock_set = *d2ccip2r_reg;

        /* Ensure HSI48 is enabled */
        if (!LL_RCC_HSI48_IsReady()) {
                LL_RCC_HSI48_Enable();
                /* Wait for HSI48 to be ready */
                uint32_t timeout = 1000;
                while (!LL_RCC_HSI48_IsReady() && timeout--) {
                        k_busy_wait(1);  /* 1 microsecond busy wait */
                }
                if (!LL_RCC_HSI48_IsReady()) {
                        LOG_WRN("HSI48 failed to stabilize");
                }
        }

        /* STM32H743 D2CCIP2R[21:20] USBSEL: 00b disabled, 01b PLL1Q, 10b PLL3Q,
         * 11b HSI48 - the correct value here.
         * LL_RCC_USB_CLKSOURCE_HSI48 = USBSEL_1|USBSEL_0 = 0x00300000. */
        LL_RCC_SetUSBClockSource(LL_RCC_USB_CLKSOURCE_HSI48);

        g_usb_d2ccip2r_after_clock_set = *d2ccip2r_reg;
        g_usb_clock_source_read = LL_RCC_GetUSBClockSource(0);
}
#endif

