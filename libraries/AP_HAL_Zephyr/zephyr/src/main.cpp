/* Keep DFU detached unless explicitly requested in config. */
static const char *const class_blocklist[] = {
        "dfu_dfu",
        NULL,
};

K_SEM_DEFINE(dtr_sem, 0, 1);

K_SEM_DEFINE(usb_init_done_sem, 0, 1);
K_THREAD_STACK_DEFINE(usb_init_stack, 2048);

static struct k_thread usb_init_thread;
static volatile int g_usb_init_worker_ret = 0;

static void usb_init_worker(void *p1, void *p2, void *p3)
{
        struct usbd_context *ctx = (struct usbd_context *)p1;

        ARG_UNUSED(p2);
        ARG_UNUSED(p3);

#if defined(CONFIG_SOC_SERIES_STM32H7X)
        /* The ArduPilot bootloader enumerated this OTG core for DFU moments
         * before jumping to us and leaves it mid-session; USB_CoreReset()
         * (GRSTCTL.CSRST) never completes on the leftover state.  Pulse the
         * RCC block reset so the core starts from virgin hardware. */
        {
                volatile uint32_t *ahb1rstr = (volatile uint32_t *)0x58024480;
                *ahb1rstr |= (1U << 27);   /* USB2OTGRST (OTG_FS) */
                k_busy_wait(10);
                *ahb1rstr &= ~(1U << 27);
                k_busy_wait(100);
        }
#endif

        g_usb_init_worker_ret = usbd_init(ctx);
        k_sem_give(&usb_init_done_sem);
}

static int usbd_init_with_timeout(struct usbd_context *ctx, k_timeout_t timeout)
{
        k_tid_t tid;

        g_usb_init_worker_ret = -ETIMEDOUT;
        k_sem_reset(&usb_init_done_sem);

        tid = k_thread_create(&usb_init_thread,
                              usb_init_stack,
                              K_THREAD_STACK_SIZEOF(usb_init_stack),
                              usb_init_worker,
                              ctx, NULL, NULL,
                              K_PRIO_PREEMPT(8), 0, K_NO_WAIT);
        if (tid == NULL) {
                return -ENOMEM;
        }

        if (k_sem_take(&usb_init_done_sem, timeout) == 0) {
                return g_usb_init_worker_ret;
        }

        k_thread_abort(tid);
        return -ETIMEDOUT;
}

/* ── USB event callback ────────────────────────────────────────────────── */
static void usb_msg_cb(struct usbd_context *const ctx,
                       const struct usbd_msg *msg)
{
        g_usb_last_msg = (uint32_t)msg->type;
        LOG_INF("USBD message: %s", usbd_msg_type_string(msg->type));

        if (msg->type == USBD_MSG_CDC_ACM_CONTROL_LINE_STATE) {
                uint32_t dtr = 0U;

                (void)uart_line_ctrl_get(msg->dev, UART_LINE_CTRL_DTR, &dtr);
                if (dtr != 0U) {
                        k_sem_give(&dtr_sem);
                }
        }

        if (usbd_can_detect_vbus(ctx)) {
                if (msg->type == USBD_MSG_VBUS_READY) {
                        if (usbd_enable(ctx)) {
                                LOG_ERR("Failed to enable USB device support");
                        }
                }

                if (msg->type == USBD_MSG_VBUS_REMOVED) {
                        if (usbd_disable(ctx)) {
                                LOG_ERR("Failed to disable USB device support");
                        }
                }
        }
}

/* ── USB device bring-up ───────────────────────────────────────────────── */
static int enable_usb_device_next(void)
{
        int err;

        g_usb_phase = 10U;
        err = usbd_add_descriptor(&cube_usbd, &cube_lang);
        if (err) {
                g_usb_err_phase = 10;
                g_usb_last_err = err;
                LOG_ERR("Failed to add lang descriptor (%d)", err);
                return err;
        }

        g_usb_phase = 20U;
        err = usbd_add_descriptor(&cube_usbd, &cube_mfr);
        if (err) {
                g_usb_err_phase = 20;
                g_usb_last_err = err;
                LOG_ERR("Failed to add mfr descriptor (%d)", err);
                return err;
        }

        g_usb_phase = 30U;
        err = usbd_add_descriptor(&cube_usbd, &cube_product);
        if (err) {
                g_usb_err_phase = 30;
                g_usb_last_err = err;
                LOG_ERR("Failed to add product descriptor (%d)", err);
                return err;
        }

        /* RT1176 OTG1 is high-speed and the stack keeps a descriptor set per speed.
         * Registering only FS leaves no configuration for the speed it enumerates
         * at, so EP0 reads go unanswered: "device not accepting address". */
        g_usb_phase = 35U;
        if (USBD_SUPPORTS_HIGH_SPEED &&
            usbd_caps_speed(&cube_usbd) == USBD_SPEED_HS) {
                err = usbd_add_configuration(&cube_usbd, USBD_SPEED_HS, &cube_hs_config);
                if (err) {
                        g_usb_err_phase = 35;
                        g_usb_last_err = err;
                        LOG_ERR("Failed to add HS configuration (%d)", err);
                        return err;
                }

                g_usb_phase = 36U;
                err = usbd_register_all_classes(&cube_usbd, USBD_SPEED_HS, 1U, class_blocklist);
                if (err) {
                        g_usb_err_phase = 36;
                        g_usb_last_err = err;
                        LOG_ERR("Failed to register HS classes (%d)", err);
                        return err;
                }

                usbd_device_set_code_triple(&cube_usbd, USBD_SPEED_HS,
                                            USB_BCC_MISCELLANEOUS, 0x02U, 0x01U);
        }

        g_usb_phase = 40U;
        err = usbd_add_configuration(&cube_usbd, USBD_SPEED_FS, &cube_fs_config);
        if (err) {
                g_usb_err_phase = 40;
                g_usb_last_err = err;
                LOG_ERR("Failed to add FS configuration (%d)", err);
                return err;
        }

        /* Register all class instances (CDC ACM) for FS configuration 1 */
        g_usb_phase = 50U;
        err = usbd_register_all_classes(&cube_usbd, USBD_SPEED_FS, 1U, class_blocklist);
        if (err) {
                g_usb_err_phase = 50;
                g_usb_last_err = err;
                LOG_ERR("Failed to register classes (%d)", err);
                return err;
        }

        /* CDC ACM uses IAD — set composite device class triple accordingly */
        usbd_device_set_code_triple(&cube_usbd, USBD_SPEED_FS,
                                    USB_BCC_MISCELLANEOUS, 0x02U, 0x01U);
        usbd_self_powered(&cube_usbd, true);

#if defined(CONFIG_HWINFO)
        g_usb_phase = 60U;
        err = usbd_add_descriptor(&cube_usbd, &cube_sn);
        if (err) {
                g_usb_err_phase = 60;
                g_usb_last_err = err;
                LOG_ERR("Failed to add serial descriptor (%d)", err);
                return err;
        }
#endif

        g_usb_phase = 70U;
        err = usbd_msg_register_cb(&cube_usbd, usb_msg_cb);
        if (err) {
                g_usb_err_phase = 70;
                g_usb_last_err = err;
                LOG_ERR("Failed to register message callback (%d)", err);
                return err;
        }

        g_usb_phase = 80U;
#if AP_ZEPHYR_USB_DEBUG_SNAPSHOTS
        snapshot_usb_regs_before();
#endif
        int init_err = usbd_init_with_timeout(&cube_usbd, K_MSEC(30000));
        g_usb_init_ret = init_err;
#if AP_ZEPHYR_USB_DEBUG_SNAPSHOTS
        snapshot_usb_regs_after();
#endif
        if (init_err) {
                g_usb_err_phase = 80;
                g_usb_last_err = init_err;
                if (init_err == -ETIMEDOUT) {
                        g_usb_phase = 85U;
                        LOG_ERR("usbd_init() timed out; skipping usbd_enable() and continuing");
                        return init_err;
                }
                LOG_ERR("usbd_init() returned %d; attempting enable anyway", init_err);
        }

        /* Hardwire assumption: always assume USB is connected for testing.
         * Try to enable immediately, regardless of usbd_init() result.
         */
        g_usb_phase = 90U;
        g_usb_phase = 100U;
        int enable_err = usbd_enable(&cube_usbd);
        g_usb_enable_ret = enable_err;
#if AP_ZEPHYR_USB_DEBUG_SNAPSHOTS
        snapshot_usb_runtime_regs();
#endif
        if (enable_err) {
                g_usb_err_phase = 100;
                g_usb_last_err = enable_err;
                LOG_ERR("usbd_enable() returned %d", enable_err);
                return enable_err;
        }

#if defined(CONFIG_SOC_SERIES_STM32H7X)
        /* Debug bring-up: force clear soft-disconnect in case HAL leaves SDIS set. */
        volatile uint32_t *const dctl_reg = (volatile uint32_t *)0x40080804U;
        *dctl_reg &= ~0x00000002U;
#if AP_ZEPHYR_USB_DEBUG_SNAPSHOTS
        snapshot_usb_runtime_regs();
#endif
#endif /* CONFIG_SOC_SERIES_STM32H7X */

        /* If we reach here, enable succeeded */
        err = 0;

        g_usb_phase = 110U;
        g_usb_err_phase = 0;
        g_usb_last_err = 0;
        return 0;
}
#endif /* CONFIG_USB_DEVICE_STACK_NEXT */

