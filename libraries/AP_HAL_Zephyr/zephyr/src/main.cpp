/* ── Entry point ───────────────────────────────────────────────────────── */

/* Zero the libc heap before ArduPilot runs: newlib malloc returns uninitialised
 * memory, so early objects start with heap garbage from previous boots and
 * fault. Zero from __bss_end to _heap_sentry, leaving ROM/WiFi vars above it. */
extern char __bss_end[];
extern char _heap_sentry[];
static void ap_extra_bss_zero(void)
{
#if defined(CONFIG_SOC_SERIES_ESP32S3)
        char *heap_start = __bss_end;       /* _end = 0x3fcd4b68 */
        char *heap_end   = _heap_sentry;    /* procpu_dram_end = 0x3fce9704 */
        if (heap_start < heap_end) {
                memset(heap_start, 0, (size_t)(heap_end - heap_start));
        }
#endif
}

int main(void)
{
        /* Earliest possible diagnostic — if this prints, app is running */
        printk("\n\n*** MAIN() STARTED ***\n");

        /* Force immediate output even if logging isn't set up yet */
        fprintf(stderr, "\n\n=== MAIN ENTERED ===\n");
        fflush(stderr);

        g_grstctl_post_reset = 0xAAAAAAAAU; /* marker: main() entered */
        g_usb_ret = -998;                   /* marker: before USB init */
        g_usb_phase = 1U;

        if (gpio_is_ready_dt(&led_amber)) {
                (void)gpio_pin_configure_dt(&led_amber, GPIO_OUTPUT_INACTIVE);
        }

        g_usb_phase = 2U;
#if defined(CONFIG_SOC_SERIES_STM32H7X)
        g_usb_phase = 11U;
        stm32h7_prime_usb_pwr();
        g_usb_phase = 12U;
        g_usb_phase = 13U;
        stm32h7_force_usb_clock_hsi48();
        g_usb_phase = 14U;
        g_usb_phase = 15U;
        stm32h7_bootloader_style_usb_reinit();
        g_usb_phase = 16U;
#endif
        g_usb_phase = 17U;
#if defined(CONFIG_USB_DEVICE_STACK_NEXT)
#if !defined(CONFIG_CDC_ACM_SERIAL_INITIALIZE_AT_BOOT)
        /* Manual USB init for boards (e.g. STM32) that don't use the
         * CDC_ACM_SERIAL_INITIALIZE_AT_BOOT auto-init path. */
        g_usb_ret = enable_usb_device_next();
#else
        /* CDC_ACM_SERIAL_INITIALIZE_AT_BOOT is set: Zephyr's cdc_acm_serial.c
         * already called usbd_init()+usbd_enable() at APPLICATION SYS_INIT
         * level before main() ran.  Nothing to do here. */
        g_usb_ret = 0;
#endif
        g_usb_phase = 3U;
        LOG_INF("%s: usbd=%d", CONFIG_BOARD, g_usb_ret);

        /* USB bring-up diagnostics, readable over SWD as ordinary globals. These
         * once wrote to a hard-coded 0x50000000, which does not exist on RT1176:
         * the imprecise bus fault surfaced at usbd_enable() and USB was blamed. */
        static const struct device *const udc_dev =
                DEVICE_DT_GET(DT_NODELABEL(zephyr_udc0));
        g_udc_initialized = (uint32_t)udc_is_initialized(udc_dev);
        g_udc_enabled = (uint32_t)udc_is_enabled(udc_dev);
#endif /* CONFIG_USB_DEVICE_STACK_NEXT */

        serial_probe_init();

        /* Zero any AP BSS that falls beyond Zephyr's __bss_end.
         * Must run before ardupilot_entry() initialises any C++ statics. */
        ap_extra_bss_zero();

        /* Hand off to ArduPilot.  ardupilot_entry() is defined by AP_HAL_MAIN()
         * in the vehicle/tool code (AP_MAIN == ardupilot_entry via zephyr.h).
         * The weak definition in ardupilot_stub.c lets cmake link an intermediate
         * zephyr.elf before the AP static library is available; it is overridden
         * at final link time by the real AP entry point. */
        return ardupilot_entry(0, NULL);
}

